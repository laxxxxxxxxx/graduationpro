<h2>时间管理的经典方法</h2>
<h3>1. 番茄工作法</h3>
<p>选择一个任务，专注工作25分钟，然后休息5分钟。每4个番茄钟后，休息15-30分钟。这个方法简单但非常有效，能够帮助克服拖延和保持专注。</p>
<h3>2. 艾森豪威尔矩阵</h3>
<p>将任务按照<strong>紧急</strong>和<strong>重要</strong>两个维度分类：</p>
<p>• 重要且紧急：立即做</p>
<p>• 重要不紧急：计划做（这是最需要投入时间的象限）</p>
<p>• 紧急不重要：委托或快速处理</p>
<p>• 不重要不紧急：减少或取消</p>
<h3>3. 吃掉那只青蛙</h3>
<p>每天先完成最困难、最重要的任务（"青蛙"），之后的其他事情都显得轻松。</p>
